function translateParasha(title) {
    if (PARASHA_NAMES[title]) return PARASHA_NAMES[title];
    if (title.includes('-')) {
        return title.split('-').map(p => PARASHA_NAMES[p.trim()] || p.trim()).join('-');
    }
    return title;
}
